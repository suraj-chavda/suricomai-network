//! Print `vectors/fees-v1.txt`. Each line is `protocol_bps attestation_bps attestation_min
//! relay_bps price | price protocol attestation relay_max total`, or the error code. A second
//! implementation in `verifiers/python/fees.py` must agree on every line.

use suricomai_escrow::fees::{quote, FeeSchedule, MIN_PRICE};

fn main() {
    println!("# protocol_bps attestation_bps attestation_min relay_bps price | price protocol attestation relay_max total");
    println!("# Generated by crates/suricomai-escrow/examples/export_fee_vectors.rs. A line that ends in a code is a refusal.");
    let schedules = [
        (100, 100, 2_000, 100),
        (0, 0, 0, 0),
        (1, 1, 0, 1),
        (300, 300, 100_000, 300),
        (299, 7, 12_345, 133),
        (50, 25, 500, 10),
    ];
    let prices = [
        0,
        1,
        MIN_PRICE - 1,
        MIN_PRICE,
        MIN_PRICE + 1,
        10_099,
        10_100,
        10_101,
        19_999,
        20_000,
        99_999,
        100_000,
        999_999,
        1_000_000,
        1_000_001,
        12_345_678,
        999_999_999,
        1_000_000_000,
        123_456_789_012,
        1_000_000_000_000,
        u64::MAX / 10_000,
        u64::MAX / 1_000,
        u64::MAX / 100,
        u64::MAX / 2,
        u64::MAX,
    ];
    for (p, a, m, r) in schedules {
        let schedule = FeeSchedule::new(p, a, m, r).expect("schedule");
        for price in prices {
            let result = match quote(price, &schedule) {
                Ok(q) => format!(
                    "{} {} {} {} {}",
                    q.price, q.protocol, q.attestation, q.relay_max, q.total
                ),
                Err(e) => e.code().to_string(),
            };
            println!("{p} {a} {m} {r} {price} | {result}");
        }
    }
}
